#!/usr/bin/env node
// Generates the one-time D1 initialization SQL for a fresh deployment.
//
// The panel has no runtime "first login becomes owner" path, so the first
// administrator, default profile, subscriber and subscription are provisioned
// from an operator terminal. Only the subscription token hash is written to SQL;
// the plaintext token is printed once and never persisted.

import { createHash, randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';

const CROCKFORD = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';

function ulid(now = Date.now()) {
	const random = randomBytes(10);
	let bits = 0;
	let value = 0;
	let encoded = '';
	for (const byte of random) {
		value = (value << 8) | byte;
		bits += 8;
		while (bits >= 5) {
			encoded += CROCKFORD[(value >>> (bits - 5)) & 31];
			bits -= 5;
		}
	}
	if (bits > 0) encoded += CROCKFORD[(value << (5 - bits)) & 31];

	let timeText = '';
	let ms = now;
	for (let index = 0; index < 10; index += 1) {
		timeText = CROCKFORD[ms % 32] + timeText;
		ms = Math.floor(ms / 32);
	}
	return timeText + encoded;
}

function sqlText(value) {
	return `'${String(value).replaceAll("'", "''")}'`;
}

function sqlJson(value) {
	return sqlText(JSON.stringify(value));
}

function sha256Hex(value) {
	return createHash('sha256').update(value).digest('hex');
}

/**
 * Calendar-month cycle in UTC, matching the Worker's `initialUsageCycle`: the
 * cycle starts on the first day of the current month and ends on the first day
 * of the next.
 */
function monthCycle(date) {
	const start = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), 1));
	const end = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth() + 1, 1));
	return {
		start: Math.floor(start.getTime() / 1000),
		end: Math.floor(end.getTime() / 1000),
	};
}

const { values } = parseArgs({
	options: {
		email: { type: 'string' },
		subscriber: { type: 'string', default: '默认用户' },
		profile: { type: 'string', default: '默认档案' },
		subscription: { type: 'string', default: '默认订阅' },
		out: { type: 'string', default: 'bootstrap.sql' },
	},
});

const email = values.email ?? process.env.ADMIN_EMAIL;
if (!email) {
	console.error('Missing administrator email. Pass --email or set ADMIN_EMAIL.');
	process.exit(1);
}
if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
	console.error(`Invalid administrator email: ${email}`);
	process.exit(1);
}

const now = Math.floor(Date.now() / 1000);
const cycle = monthCycle(new Date());
const adminId = ulid();
const profileId = ulid();
const subscriberId = ulid();
const subscriptionId = ulid();
const token = randomBytes(32).toString('base64url');
const normalizedEmail = email.trim().toLowerCase();

const statements = [
	`INSERT INTO admin_users (id, email, role, enabled, created_at, updated_at)
VALUES (${sqlText(adminId)}, ${sqlText(normalizedEmail)}, 'owner', 1, ${now}, ${now});`,
	`INSERT INTO subscription_profiles
  (id, name, description, node_selection, online_only, clash_base_json, proxy_groups_json, rules_json, revision, created_at, updated_at)
VALUES (${sqlText(profileId)}, ${sqlText(values.profile)}, NULL, 'all', 1, ${sqlJson({
		'mixed-port': 7890,
		'allow-lan': false,
		mode: 'rule',
		'log-level': 'info',
	})}, '[]', '[]', 1, ${now}, ${now});`,
	`INSERT INTO subscribers
  (id, name, email, status, traffic_limit_bytes, expires_at, usage_cycle_start, usage_cycle_end, created_at, updated_at)
VALUES (${sqlText(subscriberId)}, ${sqlText(values.subscriber)}, NULL, 'active', NULL, NULL, ${cycle.start}, ${cycle.end}, ${now}, ${now});`,
	`INSERT INTO subscriber_usage (subscriber_id, cycle_start, uplink_bytes, downlink_bytes, updated_at)
VALUES (${sqlText(subscriberId)}, ${cycle.start}, 0, 0, ${now});`,
	`INSERT INTO subscriptions (id, subscriber_id, profile_id, name, token_hash, revoked_at, expires_at, created_at)
VALUES (${sqlText(subscriptionId)}, ${sqlText(subscriberId)}, ${sqlText(profileId)}, ${sqlText(values.subscription)}, ${sqlText(sha256Hex(token))}, NULL, NULL, ${now});`,
	`INSERT INTO meta (k, v) VALUES ('users_ver', '0');`,
	`INSERT INTO meta (k, v) VALUES ('default_subscriber_id', ${sqlText(subscriberId)});`,
];

const sql = `-- Generated by scripts/bootstrap.mjs. Contains no plaintext secrets.\n${statements.join('\n')}\n`;
writeFileSync(values.out, sql, { mode: 0o600 });

console.log(`wrote ${values.out}`);
console.log(`administrator: ${normalizedEmail}`);
console.log(`subscriber_id: ${subscriberId}`);
console.log(`profile_id: ${profileId}`);
console.log(`subscription token (shown once): ${token}`);
console.log('');
console.log('Apply to local D1:');
console.log(`  npx wrangler d1 execute zako-panel --local --file=${values.out}`);
console.log('Apply to remote D1:');
console.log(`  npx wrangler d1 execute zako-panel --remote --file=${values.out}`);
